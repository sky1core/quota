func TestClaudeWorktreeCreateRemove(t *testing.T) {
	repo := newRepo(t)
	write(t, filepath.Join(repo, "AGENTS.md"), "# shared\n")
	git(t, repo, "add", "AGENTS.md")
	seedCommit(t, repo)

	base := t.TempDir()
	t.Setenv("AGENTS_OVERLAY_CLAUDE_WORKTREE_DIR", base)

	createJSON := `{"cwd":` + quote(repo) + `,"name":"feature1"}`
	code, out, errb := run(t, createJSON, "claude-worktree-create")
	if code != 0 {
		t.Fatalf("worktree-create: exit=%d (out=%q err=%q)", code, out, errb)
	}
	created := strings.TrimSpace(out)
	if created == "" {
		t.Fatalf("worktree-create printed no path (err=%q)", errb)
	}
	if _, err := os.Stat(created); err != nil {
		t.Fatalf("created worktree missing: %v", err)
	}

	removeJSON := `{"cwd":` + quote(repo) + `,"worktree_path":` + quote(created) + `}`
	code, out, errb = run(t, removeJSON, "claude-worktree-remove")
	if code != 0 {
		t.Fatalf("worktree-remove: exit=%d (out=%q err=%q)", code, out, errb)
	}
	if _, err := os.Stat(created); !os.IsNotExist(err) {
		t.Fatalf("worktree still present after remove: err=%v", err)
	}
}

func TestDirtyWorktreePreserved(t *testing.T) {
	repo := newRepo(t)
	write(t, filepath.Join(repo, "AGENTS.md"), "# shared\n")
	write(t, filepath.Join(repo, "AGENTS.local.md"), "# local\n")
	git(t, repo, "add", "AGENTS.md")
	seedCommit(t, repo)

	base := t.TempDir()
	t.Setenv("AGENTS_OVERLAY_CLAUDE_WORKTREE_DIR", base)

	createJSON := `{"cwd":` + quote(repo) + `,"name":"feature"}`
	code, out, errb := run(t, createJSON, "claude-worktree-create")
	if code != 0 {
		t.Fatalf("worktree-create: exit=%d (out=%q err=%q)", code, out, errb)
	}
	created := strings.TrimSpace(out)

	dirty := filepath.Join(created, "keepme.txt")
	write(t, dirty, "work in progress\n")

	removeJSON := `{"cwd":` + quote(repo) + `,"worktree_path":` + quote(created) + `}`
	code, out, errb = run(t, removeJSON, "claude-worktree-remove")
	if code == 0 {
		t.Fatalf("worktree-remove should refuse a dirty worktree (out=%q err=%q)", out, errb)
	}
	if _, err := os.Stat(created); err != nil {
		t.Fatalf("dirty worktree removed despite untracked work: %v", err)
	}
	data, err := os.ReadFile(dirty)
	if err != nil {
		t.Fatalf("dirty file not preserved: %v", err)
	}
	if string(data) != "work in progress\n" {
		t.Fatalf("dirty file changed: %q", data)
	}
}

